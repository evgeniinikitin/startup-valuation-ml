create table if not exists damodaran_industry_metrics (
  id bigint generated by default as identity primary key,
  dataset_family text not null,
  year int not null,
  industry_name text not null,
  number_of_firms int,
  current_pe double precision,
  trailing_pe double precision,
  forward_pe double precision,
  peg_ratio double precision,
  price_sales double precision,
  ev_sales double precision,
  ev_ebitda double precision,
  ev_ebit double precision,
  ev_ebit_after_tax double precision,
  beta double precision,
  cost_of_equity double precision,
  cost_of_debt double precision,
  tax_rate double precision,
  cost_of_capital double precision,
  source_file text not null,
  created_at timestamptz not null default now(),
  unique(dataset_family, year, industry_name)
);

create index if not exists damodaran_industry_metrics_year_idx
  on damodaran_industry_metrics(year);
create index if not exists damodaran_industry_metrics_family_idx
  on damodaran_industry_metrics(dataset_family);
create index if not exists damodaran_industry_metrics_industry_idx
  on damodaran_industry_metrics(industry_name);

create table if not exists damodaran_country_metrics (
  id bigint generated by default as identity primary key,
  dataset_family text not null,
  year int not null,
  country text not null,
  moody_rating text,
  default_spread double precision,
  equity_risk_premium double precision,
  country_risk_premium double precision,
  tax_rate double precision,
  source_file text not null,
  created_at timestamptz not null default now(),
  unique(dataset_family, year, country)
);

create index if not exists damodaran_country_metrics_year_idx
  on damodaran_country_metrics(year);
create index if not exists damodaran_country_metrics_country_idx
  on damodaran_country_metrics(country);
create index if not exists damodaran_country_metrics_family_idx
  on damodaran_country_metrics(dataset_family);

create table if not exists damodaran_global_companies (
  id bigint generated by default as identity primary key,
  year int,
  company_name text not null,
  exchange_ticker text,
  industry_group text,
  primary_sector text,
  country text,
  broad_group text,
  sub_group text,
  market_cap_usd double precision,
  revenue_usd double precision,
  ev_sales double precision,
  ev_ebitda double precision,
  pe_ratio double precision,
  beta double precision,
  cost_of_capital double precision,
  source_file text not null,
  created_at timestamptz not null default now(),
  unique(source_file, company_name)
);

create index if not exists damodaran_global_companies_year_idx
  on damodaran_global_companies(year);
create index if not exists damodaran_global_companies_industry_idx
  on damodaran_global_companies(industry_group);
create index if not exists damodaran_global_companies_country_idx
  on damodaran_global_companies(country);
